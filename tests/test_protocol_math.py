# ---------------------------------------------------------------------------
# Domain validation
# ---------------------------------------------------------------------------


def test_get_sqrt_price_at_tick_rejects_above_max() -> None:
    with pytest.raises(InvalidTickError):
        get_sqrt_price_at_tick(MAX_TICK + 1)


def test_get_sqrt_price_at_tick_rejects_below_min() -> None:
    with pytest.raises(InvalidTickError):
        get_sqrt_price_at_tick(MIN_TICK - 1)


def test_get_tick_at_sqrt_price_rejects_below_min() -> None:
    with pytest.raises(InvalidSqrtPriceError):
        get_tick_at_sqrt_price(MIN_SQRT_PRICE_X96 - 1)


def test_get_tick_at_sqrt_price_rejects_at_max() -> None:
    """V4 is strict: sqrtPriceX96 >= MAX_SQRT_PRICE reverts."""
    with pytest.raises(InvalidSqrtPriceError):
        get_tick_at_sqrt_price(MAX_SQRT_PRICE_X96)


def test_get_tick_at_sqrt_price_accepts_max_minus_one() -> None:
    """MAX_SQRT_PRICE - 1 is the largest valid input."""
    assert get_tick_at_sqrt_price(MAX_SQRT_PRICE_X96 - 1) == MAX_TICK - 1


# ---------------------------------------------------------------------------
# Tick monotonicity
# ---------------------------------------------------------------------------


def test_get_sqrt_price_at_tick_is_strictly_monotonic() -> None:
    """Larger ticks must yield larger sqrt prices (positive relationship)."""
    ticks = [-200_000, -100_000, -100, -1, 0, 1, 100, 100_000, 200_000]
    prices = [get_sqrt_price_at_tick(t) for t in ticks]
    for i in range(len(prices) - 1):
        assert prices[i] < prices[i + 1], (
            f"monotonicity violated at "
            f"tick {ticks[i]} ({prices[i]}) -> tick {ticks[i + 1]} ({prices[i + 1]})"
        )


def test_get_tick_at_sqrt_price_is_consistent_with_get_sqrt_price_at_tick() -> None:
    """get_tick(get_sqrt(t)) == t and get_sqrt(get_tick(p)) <= p."""
    test_ticks = [-887_272, -100_000, -100, 0, 100, 100_000, 887_271]
    for t in test_ticks:
        sp = get_sqrt_price_at_tick(t)
        assert get_tick_at_sqrt_price(sp) == t, f"tick={t} not round-tripped"


