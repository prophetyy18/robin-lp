@pytest.mark.parametrize("spacing", [1, 10, 60, 200, 32_767])
def test_max_usable_tick_aligned(spacing: int) -> None:
    """max_usable_tick(spacing) is the largest tick multiple of spacing <= MAX_TICK."""
    expected = (MAX_TICK // spacing) * spacing
    assert max_usable_tick(spacing) == expected


@pytest.mark.parametrize("spacing", [1, 10, 60, 200, 32_767])
def test_min_usable_tick_aligned(spacing: int) -> None:
    """min_usable_tick(spacing) is the smallest tick multiple of spacing >= MIN_TICK."""
    expected = -((-MIN_TICK) // spacing) * spacing
    assert min_usable_tick(spacing) == expected


