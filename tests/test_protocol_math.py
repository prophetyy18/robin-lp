"""Tests for the V4 math port (T012).

Vectors are loaded from ``tests/fixtures/protocol/math_vectors.json``,
which was generated by the Foundry oracle under ``tools/oracle/``.
Every Python output must match the pinned Solidity output exactly.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from robinhood_lp.protocol import (
    MAX_SQRT_PRICE_X96,
    MAX_TICK,
    MIN_SQRT_PRICE_X96,
    MIN_TICK,
    InvalidSqrtPriceError,
    InvalidTickError,
    get_amount0_delta,
    get_amount1_delta,
    get_liquidity_for_amounts,
    get_sqrt_price_at_tick,
    get_tick_at_sqrt_price,
    max_usable_tick,
    min_usable_tick,
)

VECTORS = json.loads(
    (Path(__file__).parent / "fixtures" / "protocol" / "math_vectors.json").read_text()
)


def _u(s: str) -> int:
    """Parse a uint literal that may be written in decimal or hex."""
    return int(s, 16) if s.startswith("0x") else int(s)


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------


def test_constants_match_oracle() -> None:
    c = VECTORS["constants"]
    assert c["MIN_TICK"] == MIN_TICK
    assert c["MAX_TICK"] == MAX_TICK
    assert _u(c["MIN_SQRT_PRICE_X96"]) == MIN_SQRT_PRICE_X96
    assert _u(c["MAX_SQRT_PRICE_X96"]) == MAX_SQRT_PRICE_X96


# ---------------------------------------------------------------------------
