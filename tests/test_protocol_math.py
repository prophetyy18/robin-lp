@pytest.mark.parametrize(
    "vector",
    VECTORS["amount_deltas"],
    ids=[v["name"] for v in VECTORS["amount_deltas"]],
)
def test_amount_deltas_match_oracle(vector: dict[str, Any]) -> None:
    pa = _u(vector["sqrt_price_a_x96"])
    pb = _u(vector["sqrt_price_b_x96"])
    liq = _u(vector["liquidity"])
    round_up = vector.get("round_up", False)
    if "amount0" in vector:
        assert get_amount0_delta(pa, pb, liq, round_up=round_up) == _u(vector["amount0"])
    elif "amount1" in vector:
        assert get_amount1_delta(pa, pb, liq, round_up=round_up) == _u(vector["amount1"])
    else:
        pytest.fail(f"vector {vector['name']!r} has neither amount0 nor amount1")


def test_amount_deltas_reject_degenerate_range() -> None:
    """pa must be strictly less than pb (V4 requirement)."""
    p = 79228162514264337593543950336
    with pytest.raises(ValueError):
        get_amount0_delta(p, p, 1)
    with pytest.raises(ValueError):
        get_amount0_delta(p + 1, p, 1)


def test_amount_deltas_reject_overlarge_liquidity() -> None:
    """liquidity must fit in uint128 (V4 enforcement)."""
    p = 79228162514264337593543950336
    with pytest.raises(ValueError):
        get_amount0_delta(p, p + 1, 1 << 128)


# ---------------------------------------------------------------------------
# LiquidityAmounts: round-trip
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "vector",
    VECTORS["liquidity_for_amounts"],
    ids=[v["name"] for v in VECTORS["liquidity_for_amounts"]],
)
def test_liquidity_for_amounts_matches_oracle(vector: dict[str, Any]) -> None:
    p = _u(vector["sqrt_price_x96"])
    pa = _u(vector["sqrt_price_a_x96"])
    pb = _u(vector["sqrt_price_b_x96"])
    a0 = _u(vector["amount0"])
    a1 = _u(vector["amount1"])
    assert get_liquidity_for_amounts(p, pa, pb, a0, a1) == _u(vector["liquidity"])


def test_liquidity_for_amounts_rejects_price_outside_range() -> None:
    """Current price must satisfy pa <= sqrt_price_x96 <= pb."""
    p = 79228162514264337593543950336  # 2^96
    pa = p - 1
    pb = p + 1
    # Below pa (strictly less than pa)
    with pytest.raises(ValueError):
        get_liquidity_for_amounts(pa - 1, pa, pb, 1, 1)
    # Above pb (strictly greater than pb)
    with pytest.raises(ValueError):
        get_liquidity_for_amounts(pb + 1, pa, pb, 1, 1)


# ---------------------------------------------------------------------------
# One-sided liquidity behavior (pinned by Foundry oracle's `a2l/asymmetric_*`)
# ---------------------------------------------------------------------------


def test_liquidity_for_amounts_one_sided_zero_returns_zero() -> None:
    """Documented V4 behavior: one-sided liquidityForAmounts with the
    non-contributing side at zero yields zero."""
    p = 79228162514264337593543950336
    pa = 78833030112140176575862854579
    pb = 79625275426524748796330556128
    # Above the range, amount1 contributes nothing; amount0 alone yields
    # the full-side liquidity.
    # Below the range, symmetric.
    # The pinned vectors cover (amount0=0, amount1>0) and (amount1=0,
    # amount0>0); this test pins that round trip behavior.
    liq0_only = get_liquidity_for_amounts(p, pa, pb, 1_000_000_000_000_000_000, 0)
    liq1_only = get_liquidity_for_amounts(p, pa, pb, 0, 1_000_000_000_000_000_000)
    # Both are zero because the V4 implementation returns min(liq0, liq1)
    # where one side is zero — see the `_meta` note in math_vectors.json.
    assert liq0_only == 0
    assert liq1_only == 0
